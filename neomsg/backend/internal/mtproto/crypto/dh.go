const DHGenerator = 3

func mustParseHex(s string) *big.Int {
	n, ok := new(big.Int).SetString(s, 16)
	if !ok {
		panic("invalid dh prime hex")
	}
	return n
}

func FactorPQ(pq int64) (p, q int32) {
	n := big.NewInt(pq)
	for i := int64(3); i*i <= pq; i += 2 {
		if new(big.Int).Mod(n, big.NewInt(i)).Sign() == 0 {
			return int32(i), int32(pq / i)
		}
	}
	return 2, int32(pq / 2)
}

func NewServerDHInner(gA [256]byte, nonce, serverNonce [16]byte) (b [256]byte, gB *big.Int, err error) {
	gB, err = rand.Int(rand.Reader, DHPrime)
	if err != nil {
		return b, nil, err
	}
	gAInt := new(big.Int).SetBytes(reverseBytes(gA[:]))
	gBInt := new(big.Int).Exp(gAInt, gB, DHPrime)
	copy(b[:], pad256(gBInt.Bytes()))
	_ = nonce
	_ = serverNonce
	return b, gB, nil
}

func ComputeAuthKey(gA, gB []byte, clientNonce, serverNonce [16]byte) [256]byte {
	gAInt := new(big.Int).SetBytes(reverseBytes(gA))
	gBInt := new(big.Int).SetBytes(gB)
	keyInt := new(big.Int).Exp(gAInt, gBInt, DHPrime)
	keyBytes := pad256(keyInt.Bytes())
	var authKey [256]byte
	copy(authKey[:], keyBytes)
	_ = clientNonce
	_ = serverNonce
	return authKey
}

func pad256(b []byte) []byte {
	if len(b) >= 256 {
		return b[len(b)-256:]
	}
	out := make([]byte, 256)
	copy(out[256-len(b):], b)
	return out
}

func reverseBytes(b []byte) []byte {
	out := make([]byte, len(b))
	for i := range b {
		out[i] = b[len(b)-1-i]
	}
	return out
}

func RandomInt128() ([16]byte, error) {
	var out [16]byte
	_, err := rand.Read(out[:])
	return out, err
}

func RandomInt64() (int64, error) {
	var b [8]byte
	if _, err := rand.Read(b[:]); err != nil {
		return 0, err
	}
	return int64(binary.LittleEndian.Uint64(b[:])), nil
}
